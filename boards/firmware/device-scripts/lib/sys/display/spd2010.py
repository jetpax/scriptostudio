"""
SPD2010 QSPI AMOLED Display Driver

Self-contained driver for the SPD2010 QSPI display controller used on
boards like the Waveshare ESP32-S3-Touch-LCD-1.46 (412×412 round AMOLED).

Requires the `qspi_lcd` C module for QSPI bus communication.

Usage:
    import qspi_lcd
    bus = qspi_lcd.Bus(host=1, sck=40, data0=46, data1=45,
                       data2=42, data3=41, cs=21, freq=40000000,
                       cmd_bits=32, param_bits=8)
    from lib.sys.display.spd2010 import Spd2010
    lcd = Spd2010(bus=bus, res=(412, 412), bl=5)

Copyright (c) 2026 Jonathan Elliot Peace
SPDX-License-Identifier: MIT

Init sequence ported from:
  lvgl_micropython/api_drivers/common_api_drivers/display/spd2010/
  Copyright (c) 2024-2025 Kevin G. Schlosser
"""

import time
import struct
import machine
from micropython import const

# QSPI command prefixes (SPD2010 protocol)
_WRITE_CMD   = const(0x02)
_WRITE_COLOR = const(0x32)

# Standard LCD commands
_CASET = const(0x2A)
_RASET = const(0x2B)
_RAMWR = const(0x2C)
_COLMOD = const(0x3A)
_SLPOUT = const(0x11)
_DISPON = const(0x29)


def _qspi_cmd(cmd):
    """Encode a command for QSPI: cmd byte in bits[15:8], 0x02 in bits[31:24]."""
    return (_WRITE_CMD << 24) | (cmd << 8)


def _qspi_color_cmd(cmd):
    """Encode a color-write command for QSPI: 0x32 prefix."""
    return (_WRITE_COLOR << 24) | (cmd << 8)


class Spd2010_hw:
    """Low-level SPD2010 hardware driver (QSPI bus)."""

    def __init__(self, *, bus, res, bl=None, rst=None, rot=0, color_bits=16):
        """
        Args:
            bus: qspi_lcd.Bus instance
            res: (width, height) tuple, e.g. (412, 412)
            bl: backlight pin number (optional, PWM)
            rst: reset pin number (optional)
            rot: rotation (0 or 2 for 180°)
            color_bits: 16 (RGB565) or 24 (RGB888)
        """
        self.bus = bus
        self.res = res
        self.rot = rot
        self.width, self.height = res
        self.color_bits = color_bits

        # Precompute QSPI-encoded commands
        self._caset = _qspi_cmd(_CASET)
        self._raset = _qspi_cmd(_RASET)
        self._ramwr = _qspi_color_cmd(_RAMWR)

        # Backlight PWM
        self.bl = None
        if bl is not None:
            pin = machine.Pin(bl, machine.Pin.OUT)
            if hasattr(machine, 'PWM'):
                self.bl = machine.PWM(pin)
            else:
                self.bl = pin

        # Reset pin
        self.rst = None
        if rst is not None:
            self.rst = machine.Pin(rst, machine.Pin.OUT)

        # Param buffer for set_params / set_memory_location
        self._param_buf = bytearray(4)
        self._param_mv = memoryview(self._param_buf)

        self.hard_reset()

    def hard_reset(self):
        if self.rst:
            self.rst.value(1)
            time.sleep_ms(10)
            self.rst.value(0)
            time.sleep_ms(20)
            self.rst.value(1)
            time.sleep_ms(120)
        self._init_sequence()

    def set_backlight(self, percent):
        if self.bl is None:
            return
        if hasattr(self.bl, 'duty_u16'):
            self.bl.duty_u16(percent * 655)
        else:
            self.bl.value(1 if percent > 0 else 0)

    def set_params(self, cmd, data=None):
        """Send a QSPI command with optional parameter data."""
        qcmd = _qspi_cmd(cmd)
        if data is not None:
            self.bus.tx_param(qcmd, data)
        else:
            self.bus.tx_param(qcmd)

    def set_memory_location(self, x1, y1, x2, y2):
        buf = self._param_buf
        buf[0] = (x1 >> 8) & 0xFF
        buf[1] = x1 & 0xFF
        buf[2] = (x2 >> 8) & 0xFF
        buf[3] = x2 & 0xFF
        self.bus.tx_param(self._caset, self._param_mv)

        buf[0] = (y1 >> 8) & 0xFF
        buf[1] = y1 & 0xFF
        buf[2] = (y2 >> 8) & 0xFF
        buf[3] = y2 & 0xFF
        self.bus.tx_param(self._raset, self._param_mv)

    def blit(self, x, y, w, h, data):
        """Write pixel data to a rectangular region."""
        self.set_memory_location(x, y, x + w - 1, y + h - 1)
        self.bus.tx_color(self._ramwr, data)

    def clear(self, color=0x0000):
        """Fill entire display with a single color (RGB565)."""
        bs = 128
        buf2 = bytearray(2)
        struct.pack_into('>h', buf2, 0, color)
        buf = bs * bytes(buf2)
        npx = self.width * self.height
        self.set_memory_location(0, 0, self.width - 1, self.height - 1)
        for _ in range(npx // bs):
            self.bus.tx_color(self._ramwr, buf)
        remainder = npx % bs
        if remainder:
            self.bus.tx_color(self._ramwr, buf2 * remainder)

    def _init_sequence(self):
        """Full SPD2010 initialization sequence.

        Ported from lvgl_micropython _spd2010_init.py.
        Uses compact (cmd, [params...]) tuple format.
        """
        p = self._param_buf
        mv = self._param_mv

        # Determine COLMOD value
        colmod = 0x55 if self.color_bits == 16 else 0x77  # RGB565 or RGB888

        # --- Init sequence (register pages + configuration) ---
        # This is the full sequence from the lvgl_micropython driver,
        # converted to direct set_params calls.

        def sp(cmd, val):
            """Set single-byte parameter."""
            p[0] = val
            self.set_params(cmd, mv[:1])

        def sp3(cmd, v0, v1, v2):
            """Set 3-byte parameter."""
            p[0] = v0; p[1] = v1; p[2] = v2
            self.set_params(cmd, mv[:3])

        def sp4(cmd, v0, v1, v2, v3):
            """Set 4-byte parameter."""
            p[0] = v0; p[1] = v1; p[2] = v2; p[3] = v3
            self.set_params(cmd, mv[:4])

        # Page 0x20,0x10,0x00 — COLMOD
        sp3(0xFF, 0x20, 0x10, 0x00)
        sp(_COLMOD, colmod)

        # Page 0x20,0x10,0x10 — Power settings
        sp3(0xFF, 0x20, 0x10, 0x10)
        sp(0x0C, 0x11); sp(0x10, 0x02); sp(0x11, 0x11)
        sp(0x15, 0x42); sp(0x16, 0x11); sp(0x1A, 0x02)
        sp(0x1B, 0x11); sp(0x61, 0x80); sp(0x62, 0x80)
        sp(0x54, 0x44); sp(0x58, 0x88); sp(0x5C, 0xCC)

        # Page 0x20,0x10,0x10 — Timing ch1
        sp3(0xFF, 0x20, 0x10, 0x10)
        sp(0x20, 0x80); sp(0x21, 0x81); sp(0x22, 0x31); sp(0x23, 0x20)
        sp(0x24, 0x11); sp(0x25, 0x11); sp(0x26, 0x12); sp(0x27, 0x12)

        # Timing ch2
        sp(0x30, 0x80); sp(0x31, 0x81); sp(0x32, 0x31); sp(0x33, 0x20)
        sp(0x34, 0x11); sp(0x35, 0x11); sp(0x36, 0x12); sp(0x37, 0x12)

        # More timing
        sp3(0xFF, 0x20, 0x10, 0x10)
        sp(0x41, 0x11); sp(0x42, 0x22); sp(0x43, 0x33)
        sp(0x49, 0x11); sp(0x4A, 0x22); sp(0x4B, 0x33)

        # Page 0x20,0x10,0x15 — Source settings bank 1
        sp3(0xFF, 0x20, 0x10, 0x15)
        for reg, val in [(0x00,0x00),(0x01,0x00),(0x02,0x00),(0x03,0x00),
                         (0x04,0x10),(0x05,0x0C),(0x06,0x23),(0x07,0x22),
                         (0x08,0x21),(0x09,0x20),(0x0A,0x33),(0x0B,0x32),
                         (0x0C,0x34),(0x0D,0x35),(0x0E,0x01),(0x0F,0x01)]:
            sp(reg, val)

        for reg, val in [(0x20,0x00),(0x21,0x00),(0x22,0x00),(0x23,0x00),
                         (0x24,0x0C),(0x25,0x10),(0x26,0x20),(0x27,0x21),
                         (0x28,0x22),(0x29,0x23),(0x2A,0x33),(0x2B,0x32),
                         (0x2C,0x34),(0x2D,0x35),(0x2E,0x01),(0x2F,0x01)]:
            sp(reg, val)

        # Page 0x20,0x10,0x16 — Source settings bank 2
        sp3(0xFF, 0x20, 0x10, 0x16)
        for reg, val in [(0x00,0x00),(0x01,0x00),(0x02,0x00),(0x03,0x00),
                         (0x04,0x08),(0x05,0x04),(0x06,0x19),(0x07,0x18),
                         (0x08,0x17),(0x09,0x16),(0x0A,0x33),(0x0B,0x32),
                         (0x0C,0x34),(0x0D,0x35),(0x0E,0x01),(0x0F,0x01)]:
            sp(reg, val)

        for reg, val in [(0x20,0x00),(0x21,0x00),(0x22,0x00),(0x23,0x00),
                         (0x24,0x04),(0x25,0x08),(0x26,0x16),(0x27,0x17),
                         (0x28,0x18),(0x29,0x19),(0x2A,0x33),(0x2B,0x32),
                         (0x2C,0x34),(0x2D,0x35),(0x2E,0x01),(0x2F,0x01)]:
            sp(reg, val)

        # Page 0x20,0x10,0x12 — MIPI / timing
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x00, 0x99); sp(0x2A, 0x28); sp(0x2B, 0x0F)
        sp(0x2C, 0x16); sp(0x2D, 0x28); sp(0x2E, 0x0F)

        # Page 0x20,0x10,0xA0
        sp3(0xFF, 0x20, 0x10, 0xA0)
        sp(0x08, 0xDC)

        # Page 0x20,0x10,0x45
        sp3(0xFF, 0x20, 0x10, 0x45)
        sp(0x01, 0x9C); sp(0x03, 0x9C)

        # Page 0x20,0x10,0x42
        sp3(0xFF, 0x20, 0x10, 0x42)
        sp(0x05, 0x2C)

        # Page 0x20,0x10,0x11 — TE
        sp3(0xFF, 0x20, 0x10, 0x11)
        sp(0x50, 0x01)

        # Page 0x20,0x10,0x00 — CASET/RASET
        sp3(0xFF, 0x20, 0x10, 0x00)
        sp4(0x2A, 0x00, 0x00, 0x01, 0x9B)
        sp4(0x2B, 0x00, 0x00, 0x01, 0x9B)

        # Page 0x20,0x10,0x40
        sp3(0xFF, 0x20, 0x10, 0x40)
        sp(0x86, 0x00)

        sp3(0xFF, 0x20, 0x10, 0x00)

        # Page 0x20,0x10,0x12
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x0D, 0x66)

        # Page 0x20,0x10,0x17
        sp3(0xFF, 0x20, 0x10, 0x17)
        sp(0x39, 0x3C)

        # Gamma tables (pages 0x31 and 0x32) — two identical gamma LUTs
        for page in [0x31, 0x32]:
            sp3(0xFF, 0x20, 0x10, page)
            gamma_data = [
                (0x38,0x03),(0x39,0xF0),(0x36,0x03),(0x37,0xE8),
                (0x34,0x03),(0x35,0xCF),(0x32,0x03),(0x33,0xBA),
                (0x30,0x03),(0x31,0xA2),(0x2E,0x03),(0x2F,0x95),
                (0x2C,0x03),(0x2D,0x7E),(0x2A,0x03),(0x2B,0x62),
                (0x28,0x03),(0x29,0x44),(0x26,0x02),(0x27,0xFC),
                (0x24,0x02),(0x25,0xD0),(0x22,0x02),(0x23,0x98),
                (0x20,0x02),(0x21,0x6F),(0x1E,0x02),(0x1F,0x32),
                (0x1C,0x01),(0x1D,0xF6),(0x1A,0x01),(0x1B,0xB8),
                (0x18,0x01),(0x19,0x6E),(0x16,0x01),(0x17,0x41),
                (0x14,0x00),(0x15,0xFD),(0x12,0x00),(0x13,0xCF),
                (0x10,0x00),(0x11,0x98),(0x0E,0x00),(0x0F,0x89),
                (0x0C,0x00),(0x0D,0x79),(0x0A,0x00),(0x0B,0x67),
                (0x08,0x00),(0x09,0x55),(0x06,0x00),(0x07,0x3F),
                (0x04,0x00),(0x05,0x28),(0x02,0x00),(0x03,0x0E),
            ]
            for reg, val in gamma_data:
                sp(reg, val)

        sp3(0xFF, 0x20, 0x10, 0x00)

        # Page 0x20,0x10,0x11 — Panel config continued
        sp3(0xFF, 0x20, 0x10, 0x11)
        sp(0x60, 0x01)
        sp(0x65, 0x03); sp(0x66, 0x38); sp(0x67, 0x04); sp(0x68, 0x34)
        sp(0x69, 0x03); sp(0x61, 0x03); sp(0x62, 0x38); sp(0x63, 0x04)
        sp(0x64, 0x34)

        # Mux settings
        sp(0x0A, 0x11); sp(0x0B, 0x20); sp(0x0C, 0x20)
        sp(0x55, 0x06)

        # Page 0x20,0x10,0x42
        sp3(0xFF, 0x20, 0x10, 0x42)
        sp(0x05, 0x3D); sp(0x06, 0x03)

        sp3(0xFF, 0x20, 0x10, 0x00)

        # Page 0x20,0x10,0x12
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x1F, 0xDC)

        # Page 0x20,0x10,0x17 — VCOM / power
        sp3(0xFF, 0x20, 0x10, 0x17)
        sp(0x11, 0xAA); sp(0x16, 0x12); sp(0x0B, 0xC3)
        sp(0x10, 0x0E); sp(0x14, 0xAA); sp(0x18, 0xA0)
        sp(0x1A, 0x80); sp(0x1F, 0x80)

        # Page 0x20,0x10,0x11
        sp3(0xFF, 0x20, 0x10, 0x11)
        sp(0x30, 0xEE)

        # Page 0x20,0x10,0x12
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x15, 0x0F)

        # Page 0x20,0x10,0x2D
        sp3(0xFF, 0x20, 0x10, 0x2D)
        sp(0x01, 0x3E)

        # Page 0x20,0x10,0x40
        sp3(0xFF, 0x20, 0x10, 0x40)
        sp(0x83, 0xC4)

        # Page 0x20,0x10,0x12 — final block
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x00, 0xCC); sp(0x36, 0xA0)
        sp(0x2A, 0x2D); sp(0x2B, 0x1E); sp(0x2C, 0x26)
        sp(0x2D, 0x2D); sp(0x2E, 0x1E); sp(0x1F, 0xE6)

        sp3(0xFF, 0x20, 0x10, 0xA0)
        sp(0x08, 0xE6)

        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x10, 0x0F)

        # Page 0x20,0x10,0x18
        sp3(0xFF, 0x20, 0x10, 0x18)
        sp(0x01, 0x01); sp(0x00, 0x1E)

        sp3(0xFF, 0x20, 0x10, 0x43)
        sp(0x03, 0x04)

        sp3(0xFF, 0x20, 0x10, 0x18)
        sp(0x3A, 0x01)

        # Page 0x20,0x10,0x50
        sp3(0xFF, 0x20, 0x10, 0x50)
        sp(0x05, 0x08)

        sp3(0xFF, 0x20, 0x10, 0x00)
        sp3(0xFF, 0x20, 0x10, 0x50)
        sp(0x00, 0xA6); sp(0x01, 0xA6)

        sp3(0xFF, 0x20, 0x10, 0x00)
        sp3(0xFF, 0x20, 0x10, 0x50)
        sp(0x08, 0x55)

        sp3(0xFF, 0x20, 0x10, 0x00)

        # Page 0x20,0x10,0x10 — Final config
        sp3(0xFF, 0x20, 0x10, 0x10)
        sp(0x0B, 0x43); sp(0x0C, 0x12); sp(0x10, 0x01); sp(0x11, 0x12)
        sp(0x15, 0x00); sp(0x16, 0x00); sp(0x1A, 0x00); sp(0x1B, 0x00)
        sp(0x61, 0x00); sp(0x62, 0x00)
        sp(0x51, 0x11); sp(0x55, 0x55); sp(0x58, 0x00); sp(0x5C, 0x00)

        # Timing reconfig
        sp3(0xFF, 0x20, 0x10, 0x10)
        sp(0x20, 0x81); sp(0x21, 0x82); sp(0x22, 0x72)
        sp(0x30, 0x00); sp(0x31, 0x00); sp(0x32, 0x00)

        sp3(0xFF, 0x20, 0x10, 0x10)
        sp(0x44, 0x44); sp(0x45, 0x55); sp(0x46, 0x66); sp(0x47, 0x77)
        sp(0x49, 0x00); sp(0x4A, 0x00); sp(0x4B, 0x00)

        sp3(0xFF, 0x20, 0x10, 0x17)
        sp(0x37, 0x00)

        # Source settings final
        sp3(0xFF, 0x20, 0x10, 0x15)
        for reg, val in [(0x04,0x08),(0x05,0x04),(0x06,0x1C),(0x07,0x1A),
                         (0x08,0x18),(0x09,0x16),(0x24,0x05),(0x25,0x09),
                         (0x26,0x17),(0x27,0x19),(0x28,0x1B),(0x29,0x1D)]:
            sp(reg, val)

        sp3(0xFF, 0x20, 0x10, 0x16)
        for reg, val in [(0x04,0x09),(0x05,0x05),(0x06,0x1D),(0x07,0x1B),
                         (0x08,0x19),(0x09,0x17),(0x24,0x04),(0x25,0x08),
                         (0x26,0x16),(0x27,0x18),(0x28,0x1A),(0x29,0x1C)]:
            sp(reg, val)

        # Page 0x20,0x10,0x18
        sp3(0xFF, 0x20, 0x10, 0x18)
        sp(0x1F, 0x02)

        # Page 0x20,0x10,0x11 — Charge pump
        sp3(0xFF, 0x20, 0x10, 0x11)
        sp(0x15, 0x99); sp(0x16, 0x99)
        sp(0x1C, 0x88); sp(0x1D, 0x88); sp(0x1E, 0x88)
        sp(0x13, 0xF0); sp(0x14, 0x34)

        # Page 0x20,0x10,0x12 — Misc
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x12, 0x89); sp(0x06, 0x06); sp(0x18, 0x00)

        # Page 0x20,0x10,0x11
        sp3(0xFF, 0x20, 0x10, 0x11)
        sp(0x0A, 0x00); sp(0x0B, 0xF0); sp(0x0C, 0xF0)
        sp(0x6A, 0x10)

        sp3(0xFF, 0x20, 0x10, 0x00)

        sp3(0xFF, 0x20, 0x10, 0x11)
        sp(0x08, 0x70); sp(0x09, 0x00)

        sp3(0xFF, 0x20, 0x10, 0x00)

        # TE on
        sp(0x35, 0x00)

        # Page 0x20,0x10,0x12
        sp3(0xFF, 0x20, 0x10, 0x12)
        sp(0x21, 0x70)

        # Page 0x20,0x10,0x2D
        sp3(0xFF, 0x20, 0x10, 0x2D)
        sp(0x02, 0x00)

        # Return to page 0
        sp3(0xFF, 0x20, 0x10, 0x00)

        # Sleep out
        sp(0x11, 0x00)
        time.sleep_ms(120)

        # Display on
        self.set_params(_DISPON)


class Spd2010_lvgl:
    """LVGL wrapper for Spd2010 — creates display driver and buffers."""

    def disp_drv_flush_cb(self, disp_drv, area, color_p):
        x1 = area.x1
        y1 = area.y1
        x2 = area.x2
        y2 = area.y2
        w = x2 - x1 + 1
        h = y2 - y1 + 1
        size = w * h * self.pixel_size
        data_view = color_p.__dereference__(size)

        if self.rgb565_swap_func:
            self.rgb565_swap_func(data_view, w * h)

        self.blit(x1, y1, w, h, data_view)
        self.disp_drv.flush_ready()

    def __init__(self, doublebuffer=True, factor=8):
        import lvgl as lv
        try:
            import lv_utils
        except ImportError:
            from lib.sys.display import lv_utils

        color_format = lv.COLOR_FORMAT.RGB565
        self.pixel_size = lv.color_format_get_size(color_format)
        self.rgb565_swap_func = lv.draw_sw_rgb565_swap

        if not lv.is_initialized():
            lv.init()

        if not lv_utils.event_loop.is_running():
            self.event_loop = lv_utils.event_loop()

        # Reuse existing display if present
        existing = lv.display_get_default()
        if existing is not None:
            self.disp_drv = existing
            self.disp_drv.set_flush_cb(self.disp_drv_flush_cb)
            return

        draw_buf1 = lv.draw_buf_create(self.width, self.height // factor,
                                        color_format, 0)
        draw_buf2 = None
        if doublebuffer:
            draw_buf2 = lv.draw_buf_create(self.width, self.height // factor,
                                            color_format, 0)

        self.disp_drv = lv.display_create(self.width, self.height)
        self.disp_drv.set_color_format(color_format)
        self.disp_drv.set_draw_buffers(draw_buf1, draw_buf2)
        self.disp_drv.set_render_mode(lv.DISPLAY_RENDER_MODE.PARTIAL)
        self.disp_drv.set_flush_cb(self.disp_drv_flush_cb)


class Spd2010(Spd2010_hw, Spd2010_lvgl):
    """Combined SPD2010 hardware + LVGL driver.

    Usage:
        lcd = Spd2010(bus=bus, res=(412, 412), bl=5, doublebuffer=True, factor=8)
    """
    def __init__(self, *, bus, res, bl=None, rst=None, rot=0,
                 color_bits=16, doublebuffer=True, factor=8):
        Spd2010_hw.__init__(self, bus=bus, res=res, bl=bl, rst=rst,
                             rot=rot, color_bits=color_bits)
        Spd2010_lvgl.__init__(self, doublebuffer=doublebuffer, factor=factor)
